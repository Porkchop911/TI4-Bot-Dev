#!/usr/bin/env bash
# Checks link_node_modules (slot copy of web/node_modules) and the zero-decision test with a fake
# live checkout in a temp dir; touches nothing outside it.
#
#   tools/nightly-smoke/test_link_node_modules.sh
set -uo pipefail
HERE=$(cd "$(dirname "$0")" && pwd)
TMP=$(mktemp -d)
trap 'rm -rf "$TMP"' EXIT
checks=0
failures=0
check() { # check <name> <actual> <expected>
  checks=$((checks + 1))
  if [ "$2" = "$3" ]; then echo "ok    $1"; else echo "FAIL  $1: expected [$3], got [$2]"; failures=$((failures + 1)); fi
}

mkdir -p "$TMP/repo/web/node_modules/pkg" "$TMP/repo/web/node_modules/.vite/deps" "$TMP/repo/web/node_modules/.vite/deps_temp_1" "$TMP/wt/web" "$TMP/reports"
echo x > "$TMP/repo/web/node_modules/pkg/index.js"
echo x > "$TMP/repo/web/node_modules/.vite/deps/react.js"
ln -s "$TMP/repo/web/node_modules" "$TMP/repo/web/node_modules/node_modules"
git -C "$TMP/wt" init -q
export NIGHTLY_REPO="$TMP/repo" NIGHTLY_REPORT_ROOT="$TMP/reports"

"$HERE/nightly.sh" link-node-modules "$TMP/wt" copy
nm="$TMP/wt/web/node_modules"
check "copy keeps the packages" "$(cat "$nm/pkg/index.js" 2>/dev/null)" x
check "copy has no self-link" "$([ -e "$nm/node_modules" ] || [ -L "$nm/node_modules" ] && echo present || echo gone)" gone
check "copy has no .vite cache" "$([ -e "$nm/.vite" ] && echo present || echo gone)" gone
check "source is untouched" "$([ -L "$TMP/repo/web/node_modules/node_modules" ] && [ -e "$TMP/repo/web/node_modules/.vite/deps/react.js" ] && echo kept)" kept

echo "== link branch links when not copying"
mkdir -p "$TMP/wt2/web"
git -C "$TMP/wt2" init -q
"$HERE/nightly.sh" link-node-modules "$TMP/wt2"
check "link points at the live modules" "$(readlink "$TMP/wt2/web/node_modules")" "$TMP/repo/web/node_modules"

echo "== zero-decision detection"
mkdir -p "$TMP/r1/trace" "$TMP/r2/trace" "$TMP/r3"
echo '{"decisions": 0}' > "$TMP/r1/trace/report.json"
echo '{"decisions": 12}' > "$TMP/r2/trace/report.json"
"$HERE/nightly.sh" run-made-decisions "$TMP/r1"; check "0 decisions" "$?" 1
"$HERE/nightly.sh" run-made-decisions "$TMP/r2"; check "12 decisions" "$?" 0
"$HERE/nightly.sh" run-made-decisions "$TMP/r3"; check "no report" "$?" 1

echo "$checks checks, $failures failures"
[ "$failures" -eq 0 ]
