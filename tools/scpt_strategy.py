def transcript_paragraphs(segments):
    paragraphs = []
    parts = []
    words = 0
    start = None
    last_end = 0
    def flush():
        nonlocal parts, words, start
        if parts:
            paragraphs.append((start, ' '.join(parts)))
        parts, words, start = [], 0, None
    for segment in segments:
        text = ' '.join(segment['text'].split())
        if not text:
            continue
        if parts and segment['start'] - last_end >= 4 and words >= 30:
            flush()
        if start is None:
            start = segment['start']
        parts.append(text)
        words += len(text.split())
        last_end = segment['end']
        if words >= 180 or (words >= 100 and text.endswith(('.', '?', '!', '"'))):
            flush()
    flush()
    return paragraphs

def write_readable_transcript(e, transcript, folder):
    paragraphs = transcript_paragraphs(transcript['segments'])
    status = 'Complete ASR draft' if transcript['complete'] else 'Partial pilot ASR draft'
    plain = f"Generated by tools/scpt_strategy.py; ASR text, not accuracy-reviewed.\n{e['title']}\n{e['url']}\n{status}. Paragraph breaks are automatic; speakers are not identified.\n\n" + '\n\n'.join(text for _, text in paragraphs) + '\n'
    target = folder / 'transcript.txt'
    if target.exists() and not target.read_text(encoding='utf-8').startswith('Generated by tools/scpt_strategy.py;'):
        raise ValueError(f'Refusing to overwrite manual transcript: {target}')
    target.write_text(plain, encoding='utf-8')
    lines = [f"# {md(e['title'])}", '', f"{status}. Paragraph breaks are automatic; speakers are not identified. Text is merged without summarization or corrections.", '', f"[Publisher episode]({e['url']})", '']
    for start, text in paragraphs:
        seconds = int(start)
        stamp = f'{seconds // 3600:02}:{seconds % 3600 // 60:02}:{seconds % 60:02}'
        lines += [f"[{stamp}]({e['url']}#t={seconds})", '', text, '']
    generated(folder / 'transcript.md', '\n'.join(lines))

def transcribe_one(e, settings, pilot, runid):
    from faster_whisper.audio import decode_audio
    if stopped(runid):
        raise RuntimeError('Stop requested; job remains resumable')
    audio_path, metadata = audio_for(e)
    config = {**settings, 'audio_sha256': metadata['sha256'], 'pilot': pilot}
    runkey = digest_bytes(json.dumps(config, sort_keys=True).encode())[:16]
    folder = episode_folder(e) / 'transcriptions' / runkey
    folder.mkdir(parents=True, exist_ok=True)
    final = folder / 'transcript.json'
    if final.exists():
        old = read(final)
        recorded = old.pop('content_sha256')
        if digest_bytes(json.dumps(old, sort_keys=True, ensure_ascii=False).encode()) != recorded:
            raise ValueError('Cached transcript content checksum changed')
        if old['episode'] != e['id'] or old['complete'] != (not pilot) or old['settings'] != config:
            raise ValueError('Retained transcript settings mismatch')
        write_readable_transcript(e, old, folder)
        if not pilot:
            write_readable_transcript(e, old, episode_folder(e))
            dump(episode_folder(e) / 'latest.json', {'path': final.relative_to(ROOT).as_posix(), 'sha256': digest_file(final)})
        return {'id': e['id'], 'status': 'cached', 'path': final.relative_to(ROOT).as_posix()}
    audio = decode_audio(str(audio_path), sampling_rate=16000)
    total = len(audio) / 16000
    begin = min(600, max(0, total - 180)) if pilot else 0
    end = min(total, begin + 180) if pilot else total
    chunk_seconds = 600
    count = math.ceil((end - begin) / chunk_seconds)
    all_segments = []
    for i in range(count):
        expected_start = begin + i * chunk_seconds
        expected_end = min(end, expected_start + chunk_seconds)
        if stopped(runid):
            raise RuntimeError('Stop requested; completed chunks retained')
        chunkfile = folder / f'chunk-{i:05d}.json'
        if chunkfile.exists():
            chunk = read(chunkfile)
            if chunk['settings'] != config or chunk['chunk'] != i:
                raise ValueError('Retained chunk does not match this run')
            recorded_hash = chunk.pop('sha256')
            if digest_bytes(json.dumps(chunk, sort_keys=True, ensure_ascii=False).encode()) != recorded_hash or chunk['start'] != expected_start or chunk['end'] != expected_end:
                raise ValueError('Retained chunk hash or range changed')
            for seg in chunk['segments']:
                if not math.isfinite(seg['start']) or not math.isfinite(seg['end']) or not expected_start <= seg['start'] <= seg['end'] <= expected_end + 1:
                    raise ValueError('Retained chunk has invalid segment timestamps')
        else:
            start = begin + i * chunk_seconds
            stop = min(end, start + chunk_seconds)
            prompt = settings['glossary']
            segments, info = MODEL.transcribe(audio[int(start * 16000):int(stop * 16000)], language='en', beam_size=5, word_timestamps=True, condition_on_previous_text=False, vad_filter=True, initial_prompt=prompt)
            records = []
            for s in segments:
                records.append({'start': start + s.start, 'end': start + s.end, 'text': s.text.strip(), 'avg_logprob': s.avg_logprob, 'compression_ratio': s.compression_ratio, 'no_speech_prob': s.no_speech_prob, 'needs_review': s.avg_logprob < -1 or s.compression_ratio > 2.4 or s.no_speech_prob > .6, 'words': [{'start': start + w.start, 'end': start + w.end, 'word': w.word, 'probability': w.probability} for w in (s.words or [])]})
            chunk = {'settings': config, 'chunk': i, 'start': start, 'end': stop, 'segments': records}
            chunk['sha256'] = digest_bytes(json.dumps(chunk, sort_keys=True, ensure_ascii=False).encode())
            dump(chunkfile, chunk)
        all_segments.extend(chunk['segments'])
        dump(folder / 'progress.json', {'episode': e['id'], 'chunks_done': i + 1, 'chunks_total': count, 'audio_seconds_done': chunk['end'], 'pilot': pilot, 'updated_at': utcnow()})
        print(f"{e['number']} chunk {i+1}/{count} audio={chunk['end']:.0f}s", flush=True)
    if not all_segments:
        raise ValueError('Whisper produced an empty transcript')
    for i, s in enumerate(all_segments):
        s['id'] = f's{i:06d}'
        if not 0 <= s['start'] <= s['end'] <= total + 1:
            raise ValueError('Out-of-range Whisper timestamps')
    payload = {'schema': 1, 'episode': e['id'], 'episode_url': e['url'], 'settings': config, 'duration_seconds': total, 'complete': not pilot, 'range': [begin, end], 'segments': all_segments, 'created_at': utcnow(), 'needs_review': sum(s['needs_review'] for s in all_segments)}
    payload['content_sha256'] = digest_bytes(json.dumps(payload, sort_keys=True, ensure_ascii=False).encode())
    dump(final, payload)
    write_readable_transcript(e, payload, folder)
    if not pilot:
        write_readable_transcript(e, payload, episode_folder(e))
        dump(episode_folder(e) / 'latest.json', {'path': final.relative_to(ROOT).as_posix(), 'sha256': digest_file(final)})
    return {'id': e['id'], 'status': 'pilot' if pilot else 'complete', 'segments': len(all_segments), 'needs_review': payload['needs_review'], 'path': final.relative_to(ROOT).as_posix()}

def alive(pid):
    if os.name == 'nt':
        kernel = ctypes.WinDLL('kernel32', use_last_error=True)
        kernel.OpenProcess.argtypes = [ctypes.c_ulong, ctypes.c_int, ctypes.c_ulong]
        kernel.OpenProcess.restype = ctypes.c_void_p
        kernel.GetExitCodeProcess.argtypes = [ctypes.c_void_p, ctypes.POINTER(ctypes.c_ulong)]
        kernel.CloseHandle.argtypes = [ctypes.c_void_p]
        handle = kernel.OpenProcess(0x1000, False, pid)
        if not handle:
            return ctypes.get_last_error() != 87
        code = ctypes.c_ulong()
        try:
            return not kernel.GetExitCodeProcess(handle, ctypes.byref(code)) or code.value == 259
        finally:
            kernel.CloseHandle(handle)
    try:
        os.kill(pid, 0)
        return True
    except ProcessLookupError:
        return False

def claim_lock(runid):
    lock = DATA / 'run.lock'
    lock.parent.mkdir(parents=True, exist_ok=True)
    if lock.exists():
        prior = read(lock)
        if prior.get('owner') != 'scpt_strategy' or alive(prior['pid']):
            raise ValueError('Another transcription runner owns the lock')
        # Only our known single stale lock is removed; cached data is never deleted.
        lock.unlink()
    with lock.open('x', encoding='utf-8') as f:
        json.dump({'owner': 'scpt_strategy', 'pid': os.getpid(), 'runid': runid}, f)
    return lock

def compute_reservation(runid, args, release=False):
    path = ROOT / 'plans/COMPUTE_QUEUE.md'
    text = path.read_text(encoding='utf-8')
    mine = f'| SCPT {runid} | Codex rule-bot | CPU {(args.workers + args.cpu_workers)}x{args.threads}, GPU {args.device} | {utcnow()[:10]} |'
    free = '| (none from Claude) | | | |'
    if release:
        owned = next((line for line in text.splitlines() if line.startswith(f'| SCPT {runid} |')), None)
        if owned:
            path.write_text(text.replace(owned, free), encoding='utf-8')
    else:
        if free not in text:
            raise ValueError('Compute queue is occupied; coordinate before starting')
        path.write_text(text.replace(free, mine), encoding='utf-8')

def local_model(name):
    os.environ['HF_HUB_DISABLE_IMPLICIT_TOKEN'] = '1'
    os.environ['HF_HOME'] = str(DATA / 'models/hf')
    manifest_path = DATA / 'models' / (name + '.json')
    if manifest_path.exists():
        saved = read(manifest_path)
        location = (ROOT / saved['snapshot_path']).resolve()
        if DATA.resolve() not in location.parents:
            raise ValueError('Model cache escapes the pipeline directory')
        for filename, expected in saved['files'].items():
            if Path(filename).name != filename:
                raise ValueError('Invalid model manifest filename')
            if digest_file(location / filename) != expected:
                raise ValueError('Model cache changed; preserve and investigate')
        return str(location), saved
    from huggingface_hub import HfApi
    from faster_whisper.utils import download_model
    repo = 'Systran/faster-whisper-' + name
    revision = HfApi(token=False).model_info(repo).sha
    location = Path(download_model(repo, cache_dir=str(DATA / 'models'), revision=revision, use_auth_token=False))
    saved = {'repo': repo, 'revision': revision, 'snapshot_path': location.relative_to(ROOT).as_posix(), 'files': {p.name: digest_file(p) for p in location.iterdir() if p.is_file()}, 'created_at': utcnow()}
    dump(manifest_path, saved)
    return str(location), saved

def dispatch_jobs(pools, episodes, pilot, runid):
    remaining = iter(episodes)
    pending = {}
    def submit(pool, settings):
        e = next(remaining, None)
        if e is not None:
            pending[pool.submit(transcribe_one, e, settings, pilot, runid)] = (e, pool, settings)
    for pool, count, settings in pools:
        for _ in range(count):
            submit(pool, settings)
    while pending:
        ready, _ = wait(pending, return_when=FIRST_COMPLETED)
        for future in ready:
            e, pool, settings = pending.pop(future)
            yield e, settings, future
            if not stopped(runid):
                submit(pool, settings)

def run(args):
    catalog = read(DATA / 'catalog.json')
    if catalog['ambiguities']:
        raise ValueError('Guide-selection ambiguities must be reviewed before transcription')
    total_workers = args.workers + args.cpu_workers
    if not 0 <= args.cpu_workers <= 8 or (args.cpu_workers and args.device != 'cuda'):
        raise ValueError('Additional CPU workers require a CUDA primary pool')
    if not 1 <= args.workers <= 8 or not 1 <= args.threads <= 16 or total_workers * args.threads > 16:
        raise ValueError('Use <=8 local workers and <=16 CPU threads in total')
    if args.device == 'cuda' and args.workers > 2:
        raise ValueError('Use at most two GPU instances to preserve VRAM headroom')
    if args.limit is not None and args.limit < 1:
        raise ValueError('Limit must be positive')
    if args.model not in ['tiny.en', 'base.en', 'small.en', 'medium.en', 'large-v3']:
        raise ValueError('Select a supported Systran Whisper model')
    if total_workers * args.threads > (os.cpu_count() or 1):
        raise ValueError('CPU thread budget exceeds this machine')
    episodes = catalog['episodes']
    if args.faction:
        selected = catalog['choices'].get(args.faction)
