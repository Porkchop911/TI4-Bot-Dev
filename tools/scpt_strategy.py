def audio_for(e):
    folder = episode_folder(e)
    folder.mkdir(parents=True, exist_ok=True)
    audio = folder / 'audio.mp3'
    meta = folder / 'audio.json'
    if audio.exists():
        if not meta.exists() or read(meta)['sha256'] != digest_file(audio):
            raise ValueError('Audio cache checksum missing or changed')
        return audio, read(meta)
    partial = folder / f'audio-{os.getpid()}.partial'
    started = time.monotonic()
    h = hashlib.sha256()
    size = 0
    with OPENER.open(urllib.request.Request(trusted(e['audio_url']), headers={'User-Agent': 'TI4StrategyResearch/1.0'}), timeout=45) as response, partial.open('xb') as f:
        declared = int(response.headers.get('Content-Length', '0'))
        if declared > 512 * 1024 * 1024:
            raise ValueError('Audio exceeds 512 MiB bound')
        while True:
            b = response.read(1024 * 1024)
            if not b:
                break
            size += len(b)
            if size > 512 * 1024 * 1024 or time.monotonic() - started > 600:
                raise ValueError('Audio download exceeded resource bound')
            h.update(b)
            f.write(b)
        f.flush()
        os.fsync(f.fileno())
        if not size or declared and size != declared:
            raise ValueError('Incomplete audio response')
        metadata = {'url': e['audio_url'], 'rss_declared_bytes': e['rss_audio_bytes'], 'bytes': size, 'sha256': h.hexdigest(), 'downloaded_at': utcnow(), 'http_content_type': response.headers.get('Content-Type')}
    dump(meta, metadata)
    os.replace(partial, audio)
    return audio, metadata

