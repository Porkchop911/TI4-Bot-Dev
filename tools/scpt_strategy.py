READABLE = DATA / 'readable'
BLOCK_SECONDS = 300
LOW_CONFIDENCE_WORD = 0.60

def clock(seconds):
    total = int(round(seconds))
    hours, remainder = divmod(total, 3600)
    minutes, secs = divmod(remainder, 60)
    return f'{hours}:{minutes:02d}:{secs:02d}' if hours else f'{minutes:02d}:{secs:02d}'

def transcript_quality(t):
    segments = t['segments']
    words = [w for s in segments for w in s.get('words', [])]
    probs = [w['probability'] for w in words]
    low = [w for w in words if w['probability'] < LOW_CONFIDENCE_WORD]
    return {
        'segments': len(segments),
        'needs_review': sum(1 for s in segments if s.get('needs_review')),
        'words': len(words),
        'mean_word_probability': round(sum(probs) / len(probs), 4) if probs else None,
        'low_confidence_words': len(low),
        'distinct_low_confidence_terms': len({norm(w['word']) for w in low if norm(w['word'])}),
    }

def render_readable(e, t):
    """Render one complete transcript as a timestamped, block-indexed Markdown draft."""
    if not t['complete']:
        raise ValueError('Readable rendering requires a complete transcript')
    q = transcript_quality(t)
    runkey = digest_bytes(json.dumps(t['settings'], sort_keys=True).encode())[:16]
    lines = [MARKER, '', f"# {md(e['title'])} \u2014 readable transcript draft", '',
        f"Episode ID: `{e['id']}` \u00b7 Publisher episode: [SCPT {e['number']}]({e['url']}) \u00b7 Published {e['published'][:10]} \u00b7 Guide type: {e['guide_kind']}",
        f"Faction IDs: {', '.join(e['factions'])} \u00b7 Audio duration: {clock(t['duration_seconds'])} ({t['duration_seconds']:.1f} s)",
        f"Raw transcript: `{episode_folder(e).relative_to(ROOT).as_posix()}/transcriptions/{runkey}/transcript.json` \u00b7 Source audio SHA256: `{t['settings']['audio_sha256']}`",
        f"ASR: `{t['settings']['model']}` on {t['settings']['device']}/{t['settings']['compute_type']}, language {t['settings']['language']}, beam {t['settings']['beam_size']}, VAD {t['settings']['vad_filter']}",
        f"Quality: {q['segments']} segments \u00b7 flagged for review {q['needs_review']} \u00b7 low-confidence words below {LOW_CONFIDENCE_WORD:.2f}: {q['low_confidence_words']} ({q['distinct_low_confidence_terms']} distinct terms) \u00b7 mean word confidence {q['mean_word_probability']}",
        '',
        'Unverified ASR draft. Timestamps are audio positions in the publisher episode, not proof of any claim. Proper nouns may be misheard. Not a public redistribution of the episode.',
        '']
    blocks = {}
    for s in t['segments']:
        blocks.setdefault(int(s['start'] // BLOCK_SECONDS), []).append(s)
    for key in sorted(blocks):
        segs = blocks[key]
        lines.append(f"## {clock(segs[0]['start'])} \u2013 {clock(segs[-1]['end'])}")
        lines.append('')
        for start, text in transcript_paragraphs(segs):
            lines += [f"[{clock(start)}]({e['url']}#t={int(start)})", '', text, '']
        flagged = [s for s in segs if s.get('needs_review')]
        if flagged:
            lines += ['Flagged spans for review: ' + '; '.join(f"{clock(s['start'])}–{clock(s['end'])}" for s in flagged), '']
        low = sorted((w for s in segs for w in s.get('words', []) if w['probability'] < LOW_CONFIDENCE_WORD), key=lambda w: (w['start'], w['word']))
        if low:
            lines.append('')
            lines.append('Low-confidence words in this block: ' + '; '.join(f"\"{w['word'].strip()}\" at {clock(w['start'])} ({w['probability']:.2f})" for w in low))
        lines.append('')
    return '\n'.join(lines) + '\n'

def write_readable(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f'.{os.getpid()}.partial')
    with tmp.open('w', encoding='utf-8', newline='\n') as f:
        f.write(text)
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)

