def utcnow():
    return datetime.now(timezone.utc).isoformat()

def digest_bytes(data):
    return hashlib.sha256(data).hexdigest()

def digest_file(path):
    h = hashlib.sha256()
    with path.open('rb') as f:
        for b in iter(lambda: f.read(1024 * 1024), b''):
            h.update(b)
    return h.hexdigest()

def dump(path, value):
    path.parent.mkdir(parents=True, exist_ok=True)
    tmp = path.with_name(path.name + f'.{os.getpid()}.partial')
    with tmp.open('w', encoding='utf-8', newline='\n') as f:
        json.dump(value, f, ensure_ascii=False, indent=2)
        f.write('\n')
        f.flush()
        os.fsync(f.fileno())
    os.replace(tmp, path)

def read(path):
    return json.loads(path.read_text(encoding='utf-8'))

def generated(path, text):
    path.parent.mkdir(parents=True, exist_ok=True)
    if path.exists() and not path.read_text(encoding='utf-8').startswith(MARKER):
        raise ValueError(f'Refusing to overwrite non-generated page: {path}')
    path.write_text(MARKER + '\n\n' + text, encoding='utf-8')

def norm(s):
    s = unicodedata.normalize('NFKD', html.unescape(s)).encode('ascii', 'ignore').decode().lower()
    return ' '.join(re.findall(r'[a-z0-9]+', s))

def md(s):
    return html.escape(str(s)).replace('[', '\\[').replace(']', '\\]').replace('|', '\\|')

def slug(s):
    return re.sub(r'[^a-z0-9]+', '-', s.lower()).strip('-')

def episode_folder(e):
    if not re.fullmatch(r'[A-Za-z0-9_-]+', e['id']):
        raise ValueError('Invalid episode ID')
    title = slug(norm(e.get('title', e['id'])))[:60].rstrip('-')
    return DATA / 'episodes' / (title + '--' + e['id'])

def trusted(url):
    p = urllib.parse.urlsplit(url)
    host = p.hostname or ''
    if p.scheme != 'https' or p.username or p.password or not (host == 'pscrb.fm' or host.endswith('.pscrb.fm') or host == 'podbean.com' or host.endswith('.podbean.com') or host == 'raw.githubusercontent.com'):
        raise ValueError(f'Unapproved source URL host: {host}')
    return url

class Redirects(urllib.request.HTTPRedirectHandler):
    def redirect_request(self, req, fp, code, msg, headers, newurl):
        trusted(newurl)
        return super().redirect_request(req, fp, code, msg, headers, newurl)

OPENER = urllib.request.build_opener(Redirects())

def fetch(url, limit=20 * 1024 * 1024):
    trusted(url)
    with OPENER.open(urllib.request.Request(url, headers={'User-Agent': 'TI4StrategyResearch/1.0'}), timeout=45) as f:
        b = f.read(limit + 1)
    if len(b) > limit:
        raise ValueError('Source exceeded byte limit')
    return b

def duration(value):
    parts = value.strip().split(':')
    return sum(int(v) * (60 ** i) for i, v in enumerate(reversed(parts))) if value else 0

def parse_feed(data, factions, now=None):
    root = ET.fromstring(data)
    now = now or datetime.now(timezone.utc)
    episodes = []
    for item in root.findall('./channel/item'):
        title = item.findtext('title', '').strip()
        if not re.search(r'\bguide\b', norm(title)):
            continue
        published = parsedate_to_datetime(item.findtext('pubDate', '')).astimezone(timezone.utc)
        if published > now:
            continue
        found = []
        for f in factions:
            fid = f['alias']
            aliases = ALIASES.get(fid, [fid, norm(f['factionName'])])
            if any(re.search(r'(?<!\w)' + re.escape(norm(a)) + r'(?!\w)', norm(title)) for a in aliases):
                found.append(fid)
        if not found:
            continue
        enclosure = item.find('enclosure')
        if enclosure is None or not enclosure.get('url'):
            raise ValueError(f'Guide has no audio enclosure: {title}')
        number = re.match(r'(?:Ep\s*)?(\d+)\s*:', title, re.I)
        guid = item.findtext('guid', '') or item.findtext('link', '')
        key = 'scpt-' + (number.group(1) if number else 'episode') + '-' + digest_bytes(guid.encode())[:12]
        episodes.append({'id': key, 'guid': guid, 'number': int(number.group(1)) if number else None, 'title': title, 'published': published.isoformat(), 'url': trusted(item.findtext('link', '')), 'audio_url': trusted(enclosure.get('url')), 'rss_audio_bytes': int(enclosure.get('length', '0')), 'duration_seconds': duration(item.findtext('{http://www.itunes.com/dtds/podcast-1.0.dtd}duration', '0')), 'factions': found, 'guide_kind': 'ultimate' if 'ultimate' in norm(title) else 'super' if 'super' in norm(title) else 'beginner' if 'beginner' in norm(title) else 'guide', 'compatibility': 'not reviewed; publication date is not a ruleset guarantee'})
    choices = {}
    ambiguities = {}
    for f in factions:
        candidates = sorted((e for e in episodes if f['alias'] in e['factions']), key=lambda e: (e['published'], e['guid']), reverse=True)
        if candidates:
            if len(candidates) > 1 and candidates[0]['published'] == candidates[1]['published']:
                ambiguities[f['alias']] = [e['id'] for e in candidates if e['published'] == candidates[0]['published']]
            choices[f['alias']] = candidates[0]['id']
    chosen = {e['id']: e for e in episodes if e['id'] in choices.values()}
    for e in chosen.values():
        e['factions'] = [fid for fid, eid in choices.items() if eid == e['id']]
    return {'schema': 1, 'discovered_at': now.isoformat(), 'feed': FEED, 'feed_sha256': digest_bytes(data), 'choices': choices, 'episodes': sorted(chosen.values(), key=lambda e: (e['published'], e['id']), reverse=True), 'missing': [f['alias'] for f in factions if f['alias'] not in choices], 'ambiguities': ambiguities}

