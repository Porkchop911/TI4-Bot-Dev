def transcript_for(e):
    pointer = episode_folder(e) / 'latest.json'
    if not pointer.exists():
        return None
    meta = read(pointer)
    path = (ROOT / meta['path']).resolve()
    if DATA.resolve() not in path.parents or digest_file(path) != meta['sha256']:
        raise ValueError('Invalid or changed transcript pointer')
    t = read(path)
    if not t['complete'] or t['episode'] != e['id']:
        raise ValueError('Pilot or wrong-episode transcript cannot populate wiki')
    expected = t.pop('content_sha256')
    if digest_bytes(json.dumps(t, sort_keys=True, ensure_ascii=False).encode()) != expected:
        raise ValueError('Transcript content checksum changed')
    return t

def citation_ok(c, catalog, refs, verified_transcripts=None):
    if c.get('kind') == 'episode':
        e = next((e for e in catalog['episodes'] if e['id'] == c.get('episode')), None)
        if not e:
            raise ValueError('Citation episode not selected')
        if verified_transcripts is None:
            t = transcript_for(e)
        else:
            if e['id'] not in verified_transcripts:
                verified_transcripts[e['id']] = transcript_for(e)
            t = verified_transcripts[e['id']]
        if t is None or not isinstance(c.get('start'), (int, float)) or not isinstance(c.get('end'), (int, float)) or not 0 <= c['start'] < c['end'] <= t['duration_seconds']:
            raise ValueError('Citation requires a complete transcript and valid timestamps')
        if not any(s['start'] < c['end'] and s['end'] > c['start'] for s in t['segments']):
            raise ValueError('Citation overlaps no transcript speech')
    elif c.get('kind') == 'document':
        ref = next((r for r in refs if r['id'] == c.get('document')), None)
        if not ref or c.get('heading') not in ref['headings']:
            raise ValueError('Unknown pinned document or heading')
    else:
        raise ValueError('Unknown citation kind')

def validate_summary(summary, catalog, nodes, refs, expected_faction=None, verified_transcripts=None):
    if summary.get('schema') != 1 or summary.get('status') != 'draft' or not isinstance(summary.get('summarizer'), str):
        raise ValueError('Summary requires schema1, draft status and summarizer attribution')
    if summary.get('faction') not in catalog['choices']:
        raise ValueError('Unknown summary faction')
    if expected_faction is not None and summary['faction'] != expected_faction:
        raise ValueError('Summary faction does not match its page')
    claims = summary.get('claims')
    if not isinstance(claims, list) or not claims:
        raise ValueError('Summary requires claims')
    for claim in claims:
        for field in ['statement', 'conditions', 'compatibility', 'uncertainty']:
            if not isinstance(claim.get(field), str) or not claim[field].strip('. '):
                raise ValueError('Claim lacks ' + field)
        if not isinstance(claim.get('components'), list) or any(cid not in nodes for cid in claim['components']):
            raise ValueError('Unknown claim component ID')
        if not isinstance(claim.get('citations'), list) or not claim['citations']:
            raise ValueError('Every claim requires source citations')
        for c in claim['citations']:
            citation_ok(c, catalog, refs, verified_transcripts)
    for edge in summary.get('connections', []):
        if edge.get('from') not in nodes or edge.get('to') not in nodes or edge.get('relation') not in ['enables', 'requires', 'synergizes-with', 'conflicts-with', 'scores', 'counters']:
            raise ValueError('Invalid strategy connection endpoints or relation')
        if not edge.get('conditions') or not edge.get('citations'):
            raise ValueError('Strategy connections require conditions and citations')
        for c in edge['citations']:
            citation_ok(c, catalog, refs, verified_transcripts)
    return summary

