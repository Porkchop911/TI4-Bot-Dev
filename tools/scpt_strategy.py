def components():
    nodes = {}
    for filename, kind in KINDS.items():
        path = CONTENT / (filename + '.json')
        if not path.exists():
            continue
        for record in read(path):
            cid = record.get('alias') or record.get('id')
            if not cid:
                continue
            key = f'{kind}:{cid}'
            nodes[key] = {'id': key, 'name': record.get('name') or record.get('title') or cid, 'source': record.get('source'), 'origin': path.relative_to(ROOT).as_posix(), 'references': [record[x] for x in ['wikiURL'] if record.get(x)], 'details': record}
    return nodes

